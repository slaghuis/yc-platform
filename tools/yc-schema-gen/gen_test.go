func TestGenerateRepoSchemas(t *testing.T) {
	files, err := loadSchemas("../../schemas/yc-event-schemas")
	if err != nil {
		t.Fatal(err)
	}
	src, err := generate(files)
	if err != nil {
		t.Fatal(err)
	}
	out := strings.Join(strings.Fields(string(src)), " ")
	for _, want := range []string{
		"// Code generated by yc-schema-gen. DO NOT EDIT.",
		`TypeIdentityVisitorCreatedV1 = "identity.visitor.created.v1"`,
		"type IdentityVisitorCreatedV1 struct {",
		"UserID string `json:\"user_id\"`",
		"TokenExpiresAt time.Time `json:\"token_expires_at\"`",
		"PreviousVisitorID *string `json:\"previous_visitor_id,omitempty\"`",
		"Hostnames []string `json:\"hostnames\"`",
		`PlatformServiceDeregisteredV1ReasonHealthCheckFailed = "health_check_failed"`,
		"UnitPrice *Money `json:\"unit_price,omitempty\"`",
		"AccessTokenJTI *string `json:\"access_token_jti,omitempty\"`",
		"func (IdentityUserLoggedInV1) EventType() string",
	} {
		if !strings.Contains(out, strings.Join(strings.Fields(want), " ")) {
			t.Errorf("generated code lacks %q", want)
		}
	}
}

func TestLoadSchemaRejectsMismatchedID(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "order", "order.placed.v1.json")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	body := `{"$id": "https://yc/schemas/order/wrong.json", "title": "order.placed.v1", "type": "object"}`
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := loadSchemas(dir); err == nil || !strings.Contains(err.Error(), "$id") {
		t.Fatalf("want $id error, got %v", err)
	}
}

func TestGenerateRejectsUnknownRef(t *testing.T) {
	s := &Schema{ID: idPrefix + "order/order.placed.v1.json", Title: "order.placed.v1", Type: typeList{"object"}}
	s.Properties = properties{keys: []string{"x"}, m: map[string]*Schema{"x": {Ref: "../cart/cart.created.v1.json"}}}
	_, err := generate([]schemaFile{{rel: "order/order.placed.v1.json", kind: kindEvent, schema: s, eventType: "order.placed.v1"}})
	if err == nil || !strings.Contains(err.Error(), "common/") {
		t.Fatalf("want ref error, got %v", err)
	}
}
