package main

import (
	"bytes"
	"fmt"
	"go/format"
	"net/url"
	"regexp"
	"strconv"
	"strings"
)

type generator struct {
	types  bytes.Buffer
	consts bytes.Buffer
	// refs maps a schema's absolute $id to its Go type name.
	refs     map[string]string
	usesTime bool
	usesJSON bool
}

func generate(files []schemaFile) ([]byte, error) {
	g := &generator{refs: map[string]string{}}
	for _, f := range files {
		if f.kind == kindCommon {
			g.refs[f.schema.ID] = commonTypeName(f.rel)
		}
	}

	var eventTypes []string
	for _, f := range files {
		switch f.kind {
		case kindCommon:
			name := g.refs[f.schema.ID]
			doc := fmt.Sprintf("%s is the %s fragment.", name, f.rel)
			if err := g.emitStruct(name, doc, f.schema, f.schema.ID); err != nil {
				return nil, fmt.Errorf("%s: %w", f.rel, err)
			}
		case kindEvent:
			name := pascal(f.eventType)
			doc := fmt.Sprintf("%s is the payload of %s.", name, f.eventType)
			if err := g.emitStruct(name, doc, f.schema, f.schema.ID); err != nil {
				return nil, fmt.Errorf("%s: %w", f.rel, err)
			}
			fmt.Fprintf(&g.types, "// EventType returns %s.\nfunc (%s) EventType() string { return Type%s }\n\n",
				f.eventType, name, name)
			eventTypes = append(eventTypes, f.eventType)
		case kindEnvelope:
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by yc-schema-gen. DO NOT EDIT.\n\npackage events\n\n")
	if g.usesJSON || g.usesTime {
		out.WriteString("import (\n")
		if g.usesJSON {
			out.WriteString("\"encoding/json\"\n")
		}
		if g.usesTime {
			out.WriteString("\"time\"\n")
		}
		out.WriteString(")\n\n")
	}
	out.WriteString("// Event types with a schema.\nconst (\n")
	for _, et := range eventTypes {
		fmt.Fprintf(&out, "Type%s = %q\n", pascal(et), et)
	}
	out.WriteString(")\n\n")
	out.WriteString("// EventTypes lists every event type with a schema, sorted.\nvar EventTypes = []string{\n")
	for _, et := range eventTypes {
		fmt.Fprintf(&out, "Type%s,\n", pascal(et))
	}
	out.WriteString("}\n\n")
	if g.consts.Len() > 0 {
		out.WriteString("// Enum values.\nconst (\n")
		out.Write(g.consts.Bytes())
		out.WriteString(")\n\n")
	}
	out.Write(g.types.Bytes())

	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

// emitStruct writes a struct for an object schema. Nested objects with
// properties become their own types, named after the parent and field.
func (g *generator) emitStruct(name, doc string, s *Schema, base string) error {
	var body bytes.Buffer
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	for _, key := range s.Required {
		if _, ok := s.Properties.m[key]; !ok {
			return fmt.Errorf("required property %q is not defined", key)
		}
	}

	for _, key := range s.Properties.keys {
		prop := s.Properties.m[key]
		field := pascal(key)
		typ, omitempty, err := g.goType(name+field, prop, required[key], base)
		if err != nil {
			return fmt.Errorf("property %q: %w", key, err)
		}
		for _, v := range prop.Enum {
			fmt.Fprintf(&g.consts, "%s%s%s = %q\n", name, field, pascal(v), v)
		}
		writeComment(&body, prop.Description)
		tag := key
		if omitempty {
			tag += ",omitempty"
		}
		fmt.Fprintf(&body, "%s %s `json:%q`\n", field, typ, tag)
	}

	writeComment(&g.types, doc)
	if s.Description != "" {
		g.types.WriteString("//\n")
		writeComment(&g.types, s.Description)
	}
	fmt.Fprintf(&g.types, "type %s struct {\n%s}\n\n", name, body.Bytes())
	return nil
}

// goType maps a property schema to a Go type. Optional and nullable
// scalars and structs become pointers; optional fields get omitempty.
func (g *generator) goType(name string, s *Schema, required bool, base string) (string, bool, error) {
	optional := !required
	if s.Ref != "" {
		target, err := resolveRef(base, s.Ref)
		if err != nil {
			return "", false, err
		}
		t, ok := g.refs[target]
		if !ok {
			return "", false, fmt.Errorf("$ref %q: only common/ fragments can be referenced", s.Ref)
		}
		return pointerIf(optional, t), optional, nil
	}

	kind, nullable := s.Type.nonNull()
	var t string
	switch kind {
	case "string":
		t = "string"
		if s.Format == "date-time" {
			t = "time.Time"
			g.usesTime = true
		}
	case "integer":
		t = "int64"
	case "number":
		t = "float64"
	case "boolean":
		t = "bool"
	case "array":
		if s.Items == nil {
			return "", false, fmt.Errorf("array without items")
		}
		elem, _, err := g.goType(name+"Item", s.Items, true, base)
		if err != nil {
			return "", false, err
		}
		return "[]" + elem, optional, nil
	case "object":
		if len(s.Properties.keys) == 0 {
			return "map[string]any", optional, nil
		}
		if err := g.emitStruct(name, name+" is a nested object.", s, base); err != nil {
			return "", false, err
		}
		t = name
	default:
		g.usesJSON = true
		return "json.RawMessage", optional, nil
	}
	return pointerIf(optional || nullable, t), optional, nil
}

func pointerIf(cond bool, t string) string {
	if cond {
		return "*" + t
	}
	return t
}

func resolveRef(base, ref string) (string, error) {
	b, err := url.Parse(base)
	if err != nil {
		return "", err
	}
	r, err := b.Parse(ref)
	if err != nil {
		return "", err
	}
	return r.String(), nil
}

var versionSuffix = regexp.MustCompile(`^(.+)\.v([0-9]+)\.json$`)

// commonTypeName names common/<name>.v<N>.json as <Name>, or <Name>V<N>
// from version 2 so later versions can coexist.
func commonTypeName(rel string) string {
	m := versionSuffix.FindStringSubmatch(strings.TrimPrefix(rel, "common/"))
	if m == nil {
		return pascal(strings.TrimSuffix(strings.TrimPrefix(rel, "common/"), ".json"))
	}
	if n, _ := strconv.Atoi(m[2]); n > 1 {
		return pascal(m[1]) + "V" + m[2]
	}
	return pascal(m[1])
}

var initialisms = map[string]string{
	"api": "API", "http": "HTTP", "id": "ID", "ip": "IP", "jti": "JTI",
	"json": "JSON", "sku": "SKU", "uri": "URI", "url": "URL", "uuid": "UUID",
}

// pascal converts snake_case, dotted and hyphenated names to Go's
// PascalCase, honouring common initialisms: "user_id" → "UserID".
func pascal(s string) string {
	var b strings.Builder
	isSep := func(r rune) bool {
		return (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9')
	}
	for _, part := range strings.FieldsFunc(s, isSep) {
		if up, ok := initialisms[part]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func writeComment(b *bytes.Buffer, text string) {
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		b.WriteString("// " + line + "\n")
	}
}
